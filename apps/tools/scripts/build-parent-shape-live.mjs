/* Writes scripts/parent-shape-live.js, the one file Kaleb pastes into the
 * browser console on the parent tool page to draft and score the cases in
 * tests/fixtures/parent-note-shape.json with his own voice profile.
 *
 * The pasted file is generated rather than written by hand so that its cases
 * and its checks cannot drift from the fixture and from
 * scripts/lib/parent-shape-checks.mjs: parent-note-shape.spec.js fails when
 * the committed file differs from what this writes. After changing either,
 * run from apps/tools:
 *
 *   node scripts/build-parent-shape-live.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runParentShapeLive } from './lib/parent-shape-live-run.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'scripts/parent-shape-live.js');

const BANNER = `/* PARENT NOTE SHAPE, LIVE. Generated by scripts/build-parent-shape-live.mjs;
 * edit the fixture, the checker or the runner, never this file.
 *
 * Paste the whole file into the browser console on tools.nooutco.me/notes/bcba/
 * while logged in. It drafts the 4 invented cases in
 * tests/fixtures/parent-note-shape.json with your style card and voice block,
 * scores each draft with scripts/lib/parent-shape-checks.mjs, prints a table
 * and puts the results and the drafts on your clipboard.
 *
 * It costs 4 drafts and sends only the invented cases below.
 *
 * The system prompt comes from the prompt store, not from this page. Until the
 * parent prompt change is deployed and re-extracted into the store, a run
 * scores the OLD prompt: a baseline to compare the after-run against. */
`;

/* The checker as page code: the same source, minus its export keyword. */
function checkerSource() {
  const src = readFileSync(path.join(ROOT, 'scripts/lib/parent-shape-checks.mjs'), 'utf8');
  const body = src.slice(src.indexOf('const QUESTION_LINE'));
  return body.replace('export function checkParentDraft', 'function checkParentDraft').trimEnd();
}

export function render() {
  const fixture = JSON.parse(readFileSync(path.join(ROOT, 'tests/fixtures/parent-note-shape.json'), 'utf8'));
  const cases = JSON.stringify(fixture.cases, null, 2).replace(/\n/g, '\n  ');
  const checker = checkerSource().replace(/\n/g, '\n  ');
  return `${BANNER}(() => {
  const CASES = ${cases};

  ${checker}

  return (${runParentShapeLive.toString()})(CASES, checkParentDraft);
})();
`;
}

/* --check writes nothing and exits 1 when the committed file is stale. The
 * spec runs it in a child process because Playwright transpiles what a test
 * imports, which would change the runner's source text under it. */
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rel = path.relative(process.cwd(), OUT);
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8') === render();
    console.log(current ? `${rel} is current` : `${rel} is stale: run node scripts/build-parent-shape-live.mjs`);
    process.exit(current ? 0 : 1);
  }
  writeFileSync(OUT, render());
  console.log(`wrote ${rel}`);
}
