/* Writes assets/english-words.js, the English word list the scrubber reads to
 * tell a lowercase name ("kaelen") from a lowercase word ("kale").
 *
 * Kaleb's ruling on his Masking Quality review, 2026-10-04: SCOWL at size 50
 * (the spell-check size) plus the tool's own vocabulary, and a lowercase word
 * the list does not know is masked until he excuses it.
 *
 * Source: the wordlist-english package (SCOWL, Kevin Atkinson), sizes 10 to 50,
 * English plus American, British and Canadian spellings. Lowercase words only: a capitalised entry is
 * a proper noun, and proper nouns are exactly what this list must not vouch
 * for. The tool's own words (program words, clinical terms, everyday tech
 * words SCOWL lacks) live in notes-gate.js, not here, so this file is SCOWL
 * and nothing else.
 *
 * The page loads the output as a plain script before notes-gate.js, so there
 * is no build step at run time. Rerun after changing the size:
 *
 *   node scripts/build-english-words.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(ROOT, 'package.json'));
const PKG = path.dirname(require.resolve('wordlist-english/package.json'));
export const OUT = path.join(ROOT, 'assets/english-words.js');
const SIZES = [10, 20, 35, 40, 50];

export function render() {
  const words = new Set();
  for (const size of SIZES) {
    for (const variant of ['english', 'american', 'british', 'canadian']) {
      for (const w of JSON.parse(readFileSync(path.join(PKG, `${variant}-words-${size}.json`), 'utf8'))) {
        if (/^[a-z][a-z'-]*$/.test(w)) words.add(w);
      }
    }
  }
  const list = [...words].sort();
  const notice = readFileSync(path.join(PKG, 'Copyright'), 'utf8').split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n');
  return `/* English words for the notes scrubber. Generated by
 * scripts/build-english-words.mjs from SCOWL sizes ${SIZES.join(', ')}; do not edit.
 * ${list.length} lowercase words.
 *
${notice}
 */
window.NotesEnglishWords = ${JSON.stringify(list.join('\n'))};
`;
}

// --check writes nothing and exits 1 when the committed file is stale.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rel = path.relative(process.cwd(), OUT);
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8') === render();
    console.log(current ? `${rel} is current` : `${rel} is stale: run node scripts/build-english-words.mjs`);
    process.exit(current ? 0 : 1);
  }
  writeFileSync(OUT, render());
  console.log(`wrote ${rel}`);
}
